% Inicializa el objeto del sensor una sola vez afuera del bucle para ahorrar tiempo
depthDevice = imaq.VideoDevice('kinect', 2);
step(depthDevice);

% Bucle principal que recorre cada ruta de la lista
for c = 1:numel(carpetas_base)
    ruta_actual = carpetas_base(c);

    fprintf('\n=========================================\n');
    fprintf('INICIANDO TRABAJO %d de %d\n', c, numel(carpetas_base));
    fprintf('Carpeta: %s\n', ruta_actual);
    fprintf('=========================================\n');

    % Define subcarpetas automáticamente basados en la ruta actual
    rgb_folder    = fullfile(ruta_actual, "frames_color");      
    depth_folder  = fullfile(ruta_actual, "frames_profundidad_16bit");    
    output_folder = fullfile(ruta_actual, "frames_aligned");

    % Verificar que existan las carpetas de origen antes de continuar
    if ~exist(rgb_folder, 'dir') || ~exist(depth_folder, 'dir')
        warning('Saltando: No se encontró la carpeta de color o profundidad en %s', ruta_actual);
        continue; % Salta a la siguiente carpeta de la lista
    end

    if ~exist(output_folder, 'dir')
        mkdir(output_folder);
    end

    rgb_files = dir(fullfile(rgb_folder, '*.png'));
    rgb_files = sort({rgb_files.name});

    depth_files = dir(fullfile(depth_folder, '*.png'));
    depth_files = sort({depth_files.name});

    if numel(rgb_files) == 0
        warning('Carpeta vacía o sin imágenes .png. Saltando...');
        continue;
    end

    assert(numel(rgb_files) == numel(depth_files), ...
        'Número de frames RGB (%d) no coincide con depth (%d) en esta carpeta.', ...
        numel(rgb_files), numel(depth_files));

    fprintf('Procesando %d frames...\n', numel(rgb_files));

    % Bucle interno
    for i = 1:numel(rgb_files)
        rgb_path   = fullfile(rgb_folder, rgb_files{i});
        depth_path = fullfile(depth_folder, depth_files{i});

        num_rgb   = regexp(rgb_files{i}, '\d+', 'match', 'once');
        num_depth = regexp(depth_files{i}, '\d+', 'match', 'once');
        if ~strcmp(num_rgb, num_depth)
            error('DESFASE en frame %d de la carpeta %s: rgb=%s vs depth=%s', ...
                i, ruta_actual, rgb_files{i}, depth_files{i});
        end

        colorImage = imread(rgb_path);           
        depthImage = imread(depth_path);         

        ptCloud = pcfromkinect(depthDevice, depthImage, colorImage);  
        depthAligned = ptCloud.Location(:,:,3);  
        colorAligned = ptCloud.Color;  

        [~, name, ~] = fileparts(rgb_files{i});
        out_path = fullfile(output_folder, [name '.mat']);
        save(out_path, 'colorAligned', 'depthAligned');

        if mod(i, 50) == 0
            fprintf('  %d / %d frames alineados\n', i, numel(rgb_files));
        end
    end

    fprintf('Finalizado: %s\n', output_folder);
end

